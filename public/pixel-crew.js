  function bgPatternGroup(pal, pattern) {
    const g = s('g', { fill: pal.pat });
    if (pattern === 'hanok') {
      for (const x of [2, 8, 14]) g.appendChild(s('rect', { x, y: 0, width: 1, height: 20 }));
      for (const y of [2, 8, 14]) g.appendChild(s('rect', { x: 0, y, width: 20, height: 1 }));
      for (const y of [4, 10, 16]) for (const x of [4, 10, 16]) g.appendChild(s('rect', { x, y, width: 2, height: 2 }));
    } else if (pattern === 'giwa') {
      for (const y of [3, 9, 15]) {
        for (const x of [0, 6, 12, 18]) {
          g.appendChild(s('rect', { x: x + 1, y, width: 4, height: 1 }));
          g.appendChild(s('rect', { x, y: y + 1, width: 1, height: 1 }));
        }
      }
    } else {
      for (const x of [3, 9, 15]) g.appendChild(s('rect', { x, y: 0, width: 1, height: 20 }));
      for (const y of [3, 9, 15]) g.appendChild(s('rect', { x: 0, y, width: 20, height: 1 }));
    }
    return g;
  }

  function gridToGroup(grid, pal, cls) {
    const g = s('g', cls ? { class: cls } : {});
    for (let y = 0; y < 20; y++) {
      const row = grid[y] || '';
      for (let x = 0; x < 20; x++) {
        const ch = row[x];
        if (!ch || ch === '.') continue;
        const fill = pal[ch];
        if (!fill) continue;
        g.appendChild(s('rect', { x, y, width: 1, height: 1, fill }));
      }
    }
    return g;
  }

  function zGlyphGroup() {
    const g = s('g', { class: 'av-px-z' });
    Z_GLYPH.forEach((row, y) => {
      for (let x = 0; x < row.length; x++) {
        if (row[x] !== 'X') continue;
        g.appendChild(s('rect', { x: 1.5 + x * 0.85 + 0.35, y: 1.5 + y * 0.85 + 0.35, width: 0.9, height: 0.9, fill: '#08090d' }));
        g.appendChild(s('rect', { x: 1.5 + x * 0.85, y: 1.5 + y * 0.85, width: 0.9, height: 0.9, fill: '#b8c1d9' }));
      }
    });
    return g;
  }

  function renderSvg(key = 'seonbi', { size = 44, state = 'idle', showZ = true, round = 3.5 } = {}) {
    const def = SPRITES[key] || SPRITES.seonbi;
    const working = state === 'working';
    const cooling = state === 'cooling';
    const sleeping = !working;
    const svg = s('svg', {
      viewBox: '0 0 20 20', width: size, height: size,
      class: `avatar-svg av-pixel-v2${working ? ' working' : ' sleeping'}${cooling ? ' cool' : ''}`,
      'shape-rendering': 'crispEdges', role: 'img', 'aria-label': `조선 AI 픽셀 캐릭터 ${key}`,
    });
    const clipId = `pxc-${key}-${Math.random().toString(36).slice(2, 8)}`;
    svg.appendChild(s('defs', {}, s('clipPath', { id: clipId }, s('rect', { x: 0, y: 0, width: 20, height: 20, rx: round }))));
    const inner = s('g', { 'clip-path': `url(#${clipId})` });
    inner.appendChild(s('rect', { x: 0, y: 0, width: 20, height: 20, fill: def.pal.bg }));
    inner.appendChild(bgPatternGroup(def.pal, def.pattern));

    if (working) {
      inner.appendChild(gridToGroup(def.a0, def.pal, 'av-px-f0'));
      inner.appendChild(gridToGroup(def.a1, def.pal, 'av-px-f1'));
    } else {
      inner.appendChild(gridToGroup(def.sleep, def.pal, 'av-px-sleep'));
      if (showZ) inner.appendChild(zGlyphGroup());
    }
    svg.appendChild(inner);
    return svg;
  }

